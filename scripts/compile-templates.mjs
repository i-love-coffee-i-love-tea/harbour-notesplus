import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');

const indexPath = path.join(repoRoot, 'notesplus-core/assets/web/index.html');
const outPath = path.join(repoRoot, 'notesplus-core/assets/web/template.js');

let compile;
try {
  const mod = await import('@vue/compiler-dom');
  compile = mod.compile;
} catch {
  const require = createRequire(import.meta.url);
  compile = require('@vue/compiler-dom').compile;
}

if (!compile) {
  console.error('Error: Could not load compile function from @vue/compiler-dom');
  process.exit(1);
}

if (!fs.existsSync(indexPath)) {
  console.error(`Error: Source HTML file not found at ${indexPath}`);
  process.exit(1);
}

const html = fs.readFileSync(indexPath, 'utf-8');
const startTag = '<div id="app">';
const startIdx = html.indexOf(startTag);
if (startIdx === -1) {
  console.error('Error: Could not find <div id="app"> in ' + indexPath);
  process.exit(1);
}

const bodyIdx = html.indexOf('</body>');
const endIdx = html.lastIndexOf('</div>', bodyIdx !== -1 ? bodyIdx : undefined);
if (endIdx === -1 || endIdx <= startIdx) {
  console.error('Error: Could not find matching </div> for #app in ' + indexPath);
  process.exit(1);
}

const template = html.slice(startIdx + startTag.length, endIdx).trim();

const { code } = compile(template, {
  mode: 'module',
  hoistStatic: true,
  prefixIdentifiers: true
});

const output = `// Auto-generated by scripts/compile-templates.sh - DO NOT EDIT DIRECTLY\n// Source: notesplus-core/assets/web/index.html\n\n${code}\n`;

if (process.argv.includes('--check')) {
  const existing = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf-8') : '';
  if (existing !== output) {
    console.error('Error: template.js is out of date. Run ./scripts/compile-templates.sh');
    process.exit(1);
  }
  console.log('template.js is up to date.');
} else {
  fs.writeFileSync(outPath, output, 'utf-8');
  console.log(`Successfully compiled Vue template to ${outPath}`);
}
