#!/usr/bin/env -S /home/gobuki/.deno/bin/deno run --allow-read --allow-write --allow-net
/**
 * Pre-compile the Vue in-DOM template from index.html into a render function.
 * This eliminates the need for Vue's runtime template compiler (which requires eval/new Function),
 * allowing us to use the CSP-safe runtime-only Vue build.
 *
 * Usage: ./scripts/compile-template.mjs
 * Output: notesplus-core/assets/web/template-render.js
 */
import { compile } from "npm:@vue/compiler-dom@3.4.21";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const INDEX_HTML = resolve(ROOT, "notesplus-core/assets/web/index.html");
const OUTPUT = resolve(ROOT, "notesplus-core/assets/web/template-render.js");

// Read and extract template from index.html
const html = readFileSync(INDEX_HTML, "utf-8");

// Extract content inside <div id="app" ...>...</div>
// The #app div is the root — everything between its opening tag and the last </div> before <script
const appStart = html.indexOf('<div id="app"');
if (appStart === -1) {
  console.error("ERROR: Could not find <div id=\"app\" in index.html");
  Deno.exit(1);
}

// Find the end of the opening tag
const openTagEnd = html.indexOf(">", appStart) + 1;

// Find the matching closing </div> — it's the last one before <script
const scriptIdx = html.indexOf("<script", openTagEnd);
if (scriptIdx === -1) {
  console.error("ERROR: Could not find <script tag in index.html");
  Deno.exit(1);
}

// Find the last </div> before <script
const lastDivClose = html.lastIndexOf("</div>", scriptIdx);
if (lastDivClose === -1 || lastDivClose < openTagEnd) {
  console.error("ERROR: Could not find closing </div> for #app");
  Deno.exit(1);
}

const template = html.slice(openTagEnd, lastDivClose).trim();

console.log(`Extracted template: ${template.length} chars`);

// Compile with Vue's template compiler
const result = compile(template, {
  mode: "module",
  prefixIdentifiers: true,
  hoistStatic: true,
  cacheHandlers: true,
});

if (result.errors.length > 0) {
  console.error("Template compilation errors:");
  for (const err of result.errors) {
    console.error(`  - ${err.message}`);
  }
  Deno.exit(1);
}

// The compiled code uses _vue.* helpers — we need to provide them
// Replace _vue. references with the actual imports
let code = result.code;

// The compiler generates code like:
//   import { ... as _vue } from "vue"
//   export function render(_ctx, _cache) { ... }
// We need to make it import from the vendored vue module

// Write the compiled render function
const output = `// AUTO-GENERATED by scripts/compile-template.mjs — DO NOT EDIT
// Re-run the script after modifying index.html template.
import * as _vue from "/vue.runtime.esm-browser.prod.js";
${code.replace(/^import\s.*from\s.*vue.*;\s*$/m, "")}
`;

writeFileSync(OUTPUT, output);
console.log(`Written compiled render function to ${OUTPUT}`);
console.log(`Size: ${(output.length / 1024).toFixed(1)} KB`);
